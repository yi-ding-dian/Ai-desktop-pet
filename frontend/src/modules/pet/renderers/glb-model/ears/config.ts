/**
 * 耳朵形变层配置（glb-model 渲染器的内部实现细节；PetRenderer 接口零改动）。
 * v1（2026-10-15）：**耳朵"活体微动"**——直接让原耳顶点程序化地轻轻晃动
 * （不做假耳、不做遮挡、不做大幅度"耳朵表情"）。
 *
 * 背景：GLB 兔子（Meshy 静态网格，无骨骼）的两只耳朵焊死在一个固定姿态：
 * ——左耳（观察者左）向左侧大幅外张（耳轴与竖直约 54°）；右耳近乎竖直、略向后倾（约 40°）。
 * 任何情绪/状态下耳朵都不动，观感"死板"。本模块用"顶点级形变"给耳朵补上**生命感**：
 * 常驻轻晃 + 随机小耳抖 + 情绪间几度级的微姿态差（**设计基线：全部 ≤ 9°，不要"表演"**；
 * 早期"大幅垂耳"方案经用户反馈否决，参数表已收敛为微动量级）。
 *
 * ── 坐标系 ──────────────────────────────────────────────────────────────────
 * 标定数值（pivot/tip）在 **root 局部坐标**（= 渲染器"姿态根组"局部空间；脚底中心为原点，
 * y 向上，相机在 +Z 看向模型；与 pose.ts / face/config.ts 同一坐标系）。
 * 运行时 overlay 会把它一次性换算到 mesh 几何的本地空间（顶点 attribute 空间，含节点
 * 绕 X +90° 旋转与居中/贴地偏移）——见 overlay.ts 的 attach。
 *
 * ── 标定方法（2026-10-15，离线顶点分析）────────────────────────────────────
 * 直接遍历 GLB 顶点（应用节点旋转 + 居中/贴地后共 28,749 顶点），用 y 切片聚类找到
 * "头壳 → 两耳"的分裂点（y≈0.79 处由 1 簇变 2 簇），再以"耳根→耳尖"连线为轴、
 * 胶囊包络（到轴垂距 < 半径）判定耳朵顶点集合。判定质量经染色实验核验（截图见报告）：
 *   L 耳 2,246 顶点 / R 耳 2,485 顶点，两耳重叠仅 11 个（互不误伤），头壳误伤仅限
 *   耳根下方 0.02 轴向内的过渡环（角度分布规定该处恒 0，不产生可见变形）。
 * 特征实测（root 局部坐标，单位 = 模型高 1.0785）：
 *   L 耳根 (-0.125, 0.785, -0.085) → 耳尖 (-0.350, 0.955, -0.135)，轴长 0.286
 *   R 耳根 (+0.095, 0.785, -0.040) → 耳尖 (-0.020, 1.070, -0.265)，轴长 0.381
 *   （左耳更"横"——外张幅度大；右耳更长更竖、整体向后弯，两只是不对称造型）
 * 若换模型：重点重标 EAR_L / EAR_R 的数值 + 判定半径（方法：y 切片聚类定耳根，
 * 质心折线定轴；染色实验复核覆盖率）。
 */
import type { Emotion, PetState } from '../../../../../shared/protocol'

// ------------------------------------------------------------------ 耳朵几何标定（root 局部坐标）

/** 单只耳朵的标定：耳根枢轴、耳尖、判定半径、"垂下方向"（单位：世界单位） */
export interface EarSpec {
  /** 耳根（形变枢轴：一级旋转中心；此处的顶点恒不动——"耳根绝对不裂"） */
  pivot: readonly [number, number, number]
  /** 耳尖（标定用：定义耳轴方向与耳长） */
  tip: readonly [number, number, number]
  /** 判定半径：顶点到耳轴的垂距 < 此值才算耳朵（L 耳更宽故更大） */
  radius: number
  /**
   * "垂下方向"（root 空间单位向量）：roll 正值 = 耳尖朝该方向倒下。
   * 取"该耳外侧与正下方的 45° diagonal"——左耳 (−0.707, −0.707, 0)、右耳 (+0.707, −0.707, 0)。
   * 它是"垂耳动作"的铰链基准：旋转轴 = 耳轴 × 该方向（自动垂直于两者）；
   * 两耳初始姿态差异很大（左耳外张 54°、右耳竖直后倾），但"朝外下倒"的运动学语义一致。
   */
  fall: readonly [number, number, number]
}

